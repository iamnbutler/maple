// Typed loader for the GMS v270 item catalogue, and the upgrade-capability
// resolver the analysis engine asks before it proposes anything.
//
// WHY THIS EXISTS
// ---------------
// `candidates.ts` used to trust whatever gear an agent PUT at it, so it happily
// proposed impossible upgrades: star forcing a Ring of Restraint (which has no
// upgrade slots), star forcing a Genesis weapon (which is granted at a fixed
// 22★), flaming a ring (rings never take bonus stats). The catalogue is the
// ground truth those questions are answered against.
//
// The data lives in `catalogue.json`, generated by
// `scripts/build-item-catalogue.mjs` from maplestory.io GMS/270 plus the pinned
// `chablades/mapledoro` v270 manifests. DO NOT hand-edit the JSON — regenerate it.
//
// The rules themselves, and their citations, are in `rules.ts`.
//
// LOOKUP CONTRACT
// ---------------
//  * Lookup is by item NAME, case- and whitespace-insensitive, because a name is
//    all a tooltip screenshot reliably gives us. Item ids are not on tooltips.
//  * Several distinct items share one in-game name (three "Silver Blossom Ring"
//    ids, two "Destiny Shining Rod" stages). A name that resolves to several
//    entries is merged PERMISSIVELY: a capability is denied only when EVERY
//    entry with that name denies it. Suppressing an upgrade is a destructive
//    act, so we only do it when the catalogue is unanimous.
//  * An item NOT in the catalogue is never silently dropped. It falls back to
//    the slot/category rules only — which are certain — and is flagged
//    `known: false` with an `unknown-item` reason so the UI can say
//    "unrecognised item" rather than "no upgrades available".
//
// COVERAGE — READ THIS BEFORE TRUSTING AN ABSENCE
// ----------------------------------------------
// The dump is GMS **v270**, the newest maplestory.io serves (v271-v278 all
// return 500/502, and there is no `latest` alias). v270 PREDATES the Anima
// class **Ren**, so "Imugi Gem" — Ren's secondary — is genuinely not in here,
// and neither are Mo Xuan's, Sia Astelle's or Erel Light's weapons, nor Kanna's
// v266 Talisman. See `CATALOGUE_META.coverage`.
//
// Therefore: **absence is UNKNOWN, never INVALID.** `capabilities()` never
// infers a restriction from a name it could not find — it falls through to the
// SLOT rules, which are independently verified across the whole v270 dump (0 of
// 316 medals, 0 of 239 androids, 0 of 102 totems and 0 of 59 pocket items have
// any upgrade slots), and flags the item `known: false`. A weapon or secondary
// whose name is unknown keeps every capability, so a Ren main is advised
// normally rather than being told its gear does not exist.

