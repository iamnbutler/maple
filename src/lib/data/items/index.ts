/** `schema.Slot` (`ring1`, `totem2`, ...) -> `CatalogueSlot`. */
export function catalogueSlot(slot: string | undefined): CatalogueSlot | undefined {
	if (!slot) return undefined;
	const base = slot.replace(/\d+$/, '');
	if (base === 'pendant' || base === 'ring' || base === 'totem') return base as CatalogueSlot;
	return (
		[
			'weapon',
			'secondary',
			'emblem',
			'hat',
			'top',
			'bottom',
			'overall',
			'shoes',
			'gloves',
			'cape',
			'shoulder',
			'belt',
			'earrings',
			'face',
			'eye',
			'pocket',
			'badge',
			'medal',
			'heart',
			'android'
		] as const
	).find((s) => s === base);
}

/**
 * Slot families that never take star force, independent of any single item.
 * Verified against the v270 catalogue: every medal (316 at Lv100+), every
 * emblem, every pocket item, every totem, every android and every non-weapon
 * secondary has zero upgrade slots. Badges are ALMOST in this list — Ghost Ship
 * Exorcist and the Sengoku Hakase Badge are the only two that enhance — so
 * `badge` is deliberately absent and is decided per item instead.
 * Hearts / mechanical hearts DO take star force and are also absent.
 */
export const NEVER_STAR_FORCE_SLOTS: readonly CatalogueSlot[] = [
	'emblem',
	'medal',
	'pocket',
	'totem',
	'android'
];

/** formulas.md §4A §2.1. See `rules.ts` for the citation. */
export const NEVER_FLAME_SLOTS: readonly CatalogueSlot[] = [
	'secondary',
	'emblem',
	'badge',
	'medal',
	'ring',
	'android',
	'heart',
	'shoulder',
	'totem',
	'pocket'
];

/** formulas.md §4A §3.1. See `rules.ts` for the citation. */
export const NEVER_POTENTIAL_SLOTS: readonly CatalogueSlot[] = [
	'medal',
	'badge',
	'pocket',
	'android',
	'totem'
];

