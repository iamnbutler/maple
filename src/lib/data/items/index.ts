/* Types                                                                       */
/* -------------------------------------------------------------------------- */

/**
 * Canonical slot family. Coarser than `schema.Slot` (there is one `ring`, not
 * `ring1..ring4`) because an item's capabilities do not depend on which of the
 * four ring slots it happens to sit in.
 */
export type CatalogueSlot =
	| 'weapon'
	| 'secondary'
	| 'emblem'
	| 'hat'
	| 'top'
	| 'bottom'
	| 'overall'
	| 'shoes'
	| 'gloves'
	| 'cape'
	| 'shoulder'
	| 'belt'
	| 'pendant'
	| 'ring'
	| 'earrings'
	| 'face'
	| 'eye'
	| 'pocket'
	| 'badge'
	| 'medal'
	| 'heart'
	| 'android'
	| 'totem';

export interface CatalogueEntry {
	id: number;
	name: string;
	slot: CatalogueSlot;
	/** The `ItemCategory` from `src/lib/schema/item.ts`. */
	category: string;
	/** REQ LEV / base item level. */
	itemLevel: number;
	/** In-game weapon-type label ("Two-Handed Sword", "Bow", "Claw", ...). */
	weaponType?: string;
	/** Occupies the secondary slot as well as the weapon slot. */
	twoHanded?: boolean;
	setItemId?: number;
	setName?: string;
	/**
	 * RAW WZ `tuc`. mapledoro's own `_meta` warns "in-game upgrade slots equal
	 * tuc plus 1" — we never display it, we only ask whether it is 0, which is
	 * the "this item has no upgrade slots at all" signal.
	 */
	upgradeSlots: number;
	iconUrl: string;

	canStarforce: boolean;
	fixedStarforce?: number;
	canFlame: boolean;
	canPotential: boolean;
	canBonusPotential: boolean;
	superior?: boolean;
	superiorMaxStars?: number;
	rules: string[];
}

export interface CatalogueMeta {
	generatedAt: string;
	region: string;
	gameVersion: string;
	minItemLevel: number;
	sources: Record<string, string>;
	counts: Record<string, number>;
}

export interface ItemCapabilities {
	canStarforce: boolean;
	canFlame: boolean;
	canPotential: boolean;
	canBonusPotential: boolean;
	/** Set when the item comes at a star count that cannot be changed (Genesis / Destiny = 22). */
	fixedStarforce?: number;
	/** Highest reachable star count. Absent when the item takes no star force at all. */
	maxStarforce?: number;
	superior?: boolean;
	/** False when the item name is not in the catalogue (permissive fallback was used). */
	known: boolean;
	/** The catalogue entries the name resolved to, in id order. Empty when unknown. */
	entries: readonly CatalogueEntry[];
	/** `{ ruleId: human-readable reason }` for every rule that fired. */
	reasons: Record<string, string>;
}

/** The subset of `schema.Item` this module needs. */
export interface CapabilityQuery {
	name: string;
	/** `ItemCategory` from the schema; used for the unknown-item fallback. */
	category?: string;
	/** `Slot` from the schema (`ring1`, `totem2`, ...); used for the unknown-item fallback. */
	slot?: string;
	itemLevel?: number;
	/** User-confirmed Tyrant/Nova/Elite Heliseum flag, if the catalogue does not know. */
	superior?: boolean;
}

