/**
 * Per-item max-star exceptions that are NOT the Genesis/Destiny fixed-star
 * case. Taken from `starforce.MAX_STAR_EXCEPTIONS`, minus its `genesis` and
 * `destiny` rows: those match on a bare substring, which also captures the
 * Genesis Badge, the Genesis Bandana, the "Bond of Destiny" cape and four
 * "…Destiny" medals. The catalogue resolves the real weapons by id, so this
 * module handles them itself and only borrows the unambiguous rows.
 */
const NAMED_MAX_STAR_EXCEPTIONS = starforce.MAX_STAR_EXCEPTIONS.filter(
	(row) => !('fixed' in row && row.fixed)
);

function namedMaxStars(name: string): number | undefined {
	const lower = normalizeItemName(name);
	for (const row of NAMED_MAX_STAR_EXCEPTIONS) {
		if (lower.includes(row.match)) return row.maxStars;
	}
	return undefined;
}

/**
 * What this item can and cannot have done to it.
 *
 * Resolution order:
 *   1. Catalogue lookup by normalised name. If several entries share the name,
 *      capabilities are merged permissively (deny only when unanimous).
 *   2. If the name is unknown, fall back to the slot/category rules alone and
 *      flag `known: false`. This is deliberately permissive: an unrecognised
 *      item must still generate candidates, or a typo would silently delete a
 *      real upgrade from the ranking.
 */
export function capabilities(item: CapabilityQuery): ItemCapabilities {
	// `capabilities` is pure and the analysis calls it several times per item
	// (star force, flames, potential, the gear summary), and a miss walks all
	// 5,691 entries for the fuzzy pass. Memoise on the whole query.
	const cacheKey = [
		item.name,
		item.slot ?? '',
		item.category ?? '',
		item.itemLevel ?? '',
		item.superior ? '1' : ''
	].join('\u0000');
	const cached = CAPABILITY_CACHE.get(cacheKey);
	if (cached) return cached;

	const result = computeCapabilities(item);
	CAPABILITY_CACHE.set(cacheKey, result);
	return result;
}

const CAPABILITY_CACHE = new Map<string, ItemCapabilities>();

function computeCapabilities(item: CapabilityQuery): ItemCapabilities {
	const querySlot = catalogueSlot(item.slot) ?? categoryToSlot(item.category);
	const resolved = resolveByName(item.name, querySlot);
	const entries = resolved.entries;
	const ruleIds: string[] = [];

	const slot = entries.length > 0 ? entries[0].slot : querySlot;
	if (resolved.match === 'approximate') ruleIds.push('approximate-name-match');

	let canStarforce: boolean;
	let canFlame: boolean;
	let canPotential: boolean;
	let canBonusPotential: boolean;
	let fixedStarforce: number | undefined;
	let superior = item.superior === true;
	let superiorMaxStars: number | undefined;

	if (entries.length > 0) {
		// Permissive merge: deny only when every entry with this name denies.
		canStarforce = entries.some((e) => e.canStarforce);
		canFlame = entries.some((e) => e.canFlame);
		canPotential = entries.some((e) => e.canPotential);
		canBonusPotential = entries.some((e) => e.canBonusPotential);
		superior = superior || entries.some((e) => e.superior === true);

		const fixed = new Set(
			entries.map((e) => e.fixedStarforce).filter((v): v is number => v !== undefined)
		);
		if (fixed.size === 1 && entries.every((e) => e.fixedStarforce !== undefined)) {
			fixedStarforce = [...fixed][0];
		}

		const caps = entries.map((e) => e.superiorMaxStars).filter((v): v is number => v !== undefined);
		if (caps.length > 0) superiorMaxStars = Math.max(...caps);

		for (const entry of entries) {
			for (const id of entry.rules) if (!ruleIds.includes(id)) ruleIds.push(id);
		}
		// A rule only earns its reason if it actually bit after the merge.
		if (canStarforce) {
			for (const id of [
				'no-upgrade-slots',
				'liberated-weapon-fixed-star',
				'destiny-stage-ambiguous'
			]) {
				const at = ruleIds.indexOf(id);
				if (at >= 0) ruleIds.splice(at, 1);
			}
		}
		if (canFlame) drop(ruleIds, 'flame-ineligible-slot');
		if (canPotential) drop(ruleIds, 'potential-ineligible-slot');
	} else {
		ruleIds.push('unknown-item');
		canStarforce = slot === undefined || !NEVER_STAR_FORCE_SLOTS.includes(slot);
		canFlame = slot === undefined || !NEVER_FLAME_SLOTS.includes(slot);
		canPotential = slot === undefined || !NEVER_POTENTIAL_SLOTS.includes(slot);
		canBonusPotential = canPotential;
		if (!canStarforce) ruleIds.push('no-upgrade-slots');
		if (!canFlame) ruleIds.push('flame-ineligible-slot');
		if (!canPotential) ruleIds.push('potential-ineligible-slot');
	}

	// Bonus potential does not exist in Heroic — the only world scope modelled.
	if (canBonusPotential) ruleIds.push('bonus-potential-not-in-heroic');
	canBonusPotential = false;

	// The liberated-weapon family rule OVERRIDES everything above. It is keyed on
	// the name prefix rather than on a catalogue id, because Genesis and Destiny
	// weapons are per-class (dozens of names) and a capture may produce a generic
	// one — "Genesis Sword", "Genesis Fan" — that no catalogue id carries.
	const family = liberatedWeaponFamily(item.name, slot, item.category);
	if (family) {
		// The family rule is authoritative, so an approximate name hit is no longer
		// interesting: "Genesis Sword" was recognised, just not as one exact id.
		drop(ruleIds, 'approximate-name-match');
		canStarforce = false;
		fixedStarforce = family.fixedStarforce;
		for (const id of [
			'no-upgrade-slots',
			'liberated-weapon-fixed-star',
			'destiny-stage-ambiguous',
			'sealed-liberation-weapon'
		]) {
			drop(ruleIds, id);
		}
		ruleIds.push(...family.rules);
	}

	/* --- max stars -------------------------------------------------------- */
	const itemLevel = item.itemLevel ?? entries[0]?.itemLevel;
	let maxStarforce: number | undefined;
	if (fixedStarforce !== undefined) {
		maxStarforce = fixedStarforce;
	} else if (canStarforce && itemLevel !== undefined) {
		maxStarforce = starforce.maxStars(itemLevel, superior);
		const named = namedMaxStars(item.name);
		if (named !== undefined) maxStarforce = Math.min(maxStarforce, named);
		if (superiorMaxStars !== undefined) maxStarforce = Math.min(maxStarforce, superiorMaxStars);
	}

	// Only report a rule as "blocking" X when X is actually blocked, and only
	// report the rules that bear on X — printing every rule that fired made the
	// star force note also explain flames and bonus potential.
	const unrecognised = entries.length === 0 ? ['unknown-item'] : [];
	const blockedFor = (
		key: 'starforce' | 'flame' | 'potential' | 'bonusPotential',
		blocked: boolean
	): string[] => {
		if (!blocked) return [];
		const own = ruleIds.filter((id) => BLOCKING_RULES[key].includes(id));
		return [...own, ...unrecognised.filter((id) => ruleIds.includes(id))];
	};

	return {
		canStarforce,
		canFlame,
		canPotential,
		canBonusPotential,
		...(fixedStarforce !== undefined ? { fixedStarforce } : {}),
		...(maxStarforce !== undefined ? { maxStarforce } : {}),
		...(superior ? { superior: true } : {}),
		known: entries.length > 0,
		matchQuality: resolved.match,
		entries,
		reasons: reasonsFor(ruleIds),
		blockedBy: {
			starforce: blockedFor('starforce', !canStarforce),
			flame: blockedFor('flame', !canFlame),
			potential: blockedFor('potential', !canPotential),
			bonusPotential: blockedFor('bonusPotential', !canBonusPotential)
		},
		...(family ? { family: family.label } : {})
	};
}

function drop(ids: string[], id: string): void {
	const at = ids.indexOf(id);
	if (at >= 0) ids.splice(at, 1);
}

/** Last-resort slot guess from the schema `ItemCategory` when no slot was given. */
function categoryToSlot(category: string | undefined): CatalogueSlot | undefined {
	switch (category) {
		case 'weapon':
		case 'secondary':
		case 'emblem':
		case 'heart':
		case 'badge':
		case 'pocket':
		case 'medal':
		case 'android':
		case 'totem':
			return category;
		// `armor` and `accessory` span several slot families with different
		// rules (a ring takes no flames, a belt does), so there is nothing safe
		// to guess — return undefined and let the fallback stay permissive.
		default:
			return undefined;
	}
}

/** The single reason string for one rule id, for callers that want just the prose. */
export function ruleReason(id: RuleId): string {
	return RULES[id].reason;
}
